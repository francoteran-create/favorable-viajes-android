#!/usr/bin/env python3
"""Verify Android monthly PDF text has no glyphs outside the printable page.

This is a geometry regression gate, not a replacement for a visual review.
Uses only the synthetic attendance PDF generated by Android CI.
"""
from pathlib import Path
import sys
import fitz

pdf = Path(sys.argv[1] if len(sys.argv) > 1 else "out/smoke/NAUTILUS_MENSUAL_PILOTO.pdf")
assert pdf.is_file() and pdf.stat().st_size > 1500, "Missing or empty monthly PDF"
doc = fitz.open(pdf)
assert len(doc) >= 1, "Monthly PDF has zero pages"
issues = []
glyphs = 0
for page_number, page in enumerate(doc, 1):
    bounds = page.rect
    assert bounds.width >= 500 and bounds.height >= 700, "Unexpected page size"
    text = page.get_text("rawdict")
    for block in text["blocks"]:
        if "lines" not in block:
            continue
        for line in block["lines"]:
            for span in line["spans"]:
                for char in span["chars"]:
                    if not char["c"].strip():
                        continue
                    glyphs += 1
                    r = fitz.Rect(char["bbox"])
                    # Small tolerance for font overshoot / PDF text geometry.
                    if (r.x0 < -1.5 or r.y0 < -1.5
                            or r.x1 > bounds.width + 1.5
                            or r.y1 > bounds.height + 1.5):
                        issues.append(f"page {page_number}: {char['c']!r} {tuple(round(v, 1) for v in r)}")
assert glyphs >= 50, f"Unexpectedly little extractable report text: {glyphs} glyphs"
if issues:
    raise AssertionError("Text spills outside A4 page:\n" + "\n".join(issues[:25]))
print(f"PASS: {len(doc)} pages, {glyphs} glyphs within A4 page geometry")
